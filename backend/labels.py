def transcript(language="English"):
    """Labels for the transcript. An unknown or untranslated language gets English.

    Falling back rather than raising is deliberate: a transcript in the wrong
    language is still readable, and a download that fails is not.
    """
    return TRANSCRIPT.get(language) or TRANSCRIPT["English"]

def briefing(language="English"):
    """Labels for the briefing. Same fallback as the transcript."""
    return BRIEFING.get(language) or BRIEFING["English"]
